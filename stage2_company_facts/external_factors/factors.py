def sector_entry(okved: str):
    for key in (okved[:5], okved[:4], okved[:2]):
        if key in SECTOR:
            return key, SECTOR[key]
    return None, ([], [], [])


def _slug(topic: str, label: str) -> str:
    return f'factor:{topic}:' + ''.join(c if c.isalnum() else '_' for c in label.lower()).strip('_')[:40]


def factors(card: dict, facts: list[dict]) -> list[dict]:
    """card: profile['card'] (stage5 fields); facts: profile['facts'] with ids. Highest weight wins per factor id."""
    fid = {}
    for f in facts:
        fid.setdefault(f['cat'], f['id'])
    out: dict[str, dict] = {}

    def add(f: F, weight: float, rule: str, basis: list[str], extra_kw=(), mechanism=None):
        topic, label, mech, kw = f
        i = _slug(topic, label)
        if i in out and out[i]['weight'] >= weight:
            out[i]['basis'] = list(dict.fromkeys(out[i]['basis'] + basis))
            return
        prev = out.get(i, {}).get('basis', [])
        out[i] = {'id': i, 'topic': topic, 'label': label, 'mechanism': mechanism or mech,
                  'keywords': list(dict.fromkeys([*kw, *extra_kw])), 'basis': list(dict.fromkeys(prev + basis)),
                  'weight': round(weight, 2), 'rule': rule}

    act = fid.get('activity', 'card.okved')
    key, (goods, inputs, sector) = sector_entry(card['okved'])
    for f in sector:
        add(f, 0.8 if key and len(key) > 2 else 0.6, f'sector:{key}', [act], goods[:3])
    for f in BASE:
        add(f, 0.3, 'base', [act])

    bank = fid.get('bank', 'card.products')
    if 'loan' in card['products'] or 'leasing' in card['products']:
        add(RATE, 1.0, 'product:loan_or_leasing', [bank],
            mechanism='у компании кредитные или лизинговые продукты: ставка напрямую меняет процентные расходы')
    if 'deposit' in card['products']:
        add(RATE, 0.7, 'product:deposit', [bank], mechanism='у компании депозиты: ставка меняет доход на свободные средства')
    if 'factoring' in card['products']:
        add(('кредит', 'Стоимость факторинга', 'стоимость финансирования дебиторки', ['факторинг', 'отсрочка платежа']), 0.7,
            'product:factoring', [bank])

    trade = fid.get('trade', 'card.fts_countries')
    for c in card['fts_countries']:
        cur = CURRENCY.get(c)
        add(('курс', f'Курс валюты: {c}', 'расчёты с контрагентами страны', ['курс рубля']), 0.8, 'fts:country', [trade],
            [w for w in (cur and f'курс {cur}', c, f'{c} торговля с Россией') if w],
            mechanism=f'внешнеторговые операции со страной {c} (направление не указано): '
                      f'курс{" " + cur if cur else " местной валюты"} и проведение платежей')
        if c in UNFRIENDLY:
            add(TRADE, 0.9, 'fts:unfriendly', [trade], [c],
                mechanism=f'операции со страной {c}: санкционные ограничения и платёжная инфраструктура')
    if card['fts_countries'] or card['fts_flag']:
        add(TRADE, 0.7, 'fts:flag', [trade], card['fts_countries'])

    own = next((f['id'] for f in facts if f['cat'] == 'ownership' and 'иностран' in f['text'].lower()), None)
    if own:
        add(('внешняя_торговля', 'Режим для компаний с иностранным участием', 'ограничения на сделки и дивиденды',
             ['компании с иностранным участием', 'контрсанкции', 'выход иностранных компаний', 'временное управление']), 0.8,
            'ownership:foreign', [own])

    for side, shares, cat in (('out', card['pay_out'], 'payments_out'), ('in', card['pay_in'], 'payments_in')):
        for div, share in sorted(shares.items(), key=lambda kv: -kv[1]):
            if share < 0.15:
                break
            if div == card['okved'][:2]:
                continue  # same division: its factors are already the company's own
            k, (g, inp, fs) = sector_entry(div)
            role = 'поставщики' if side == 'out' else 'покупатели'
            for f in fs[:2]:
                # weight stays below the own sector (0.6-0.8)
                add(f, round(min(0.6, 0.3 + 0.5 * share), 2), f'chain:{side}:{div}', [fid.get(cat, f'card.pay_{side}')], g[:2],
                    mechanism=f'{role} с ОКВЭД {div}.* — {share:.0%} {"исходящих" if side == "out" else "входящих"} платежей '
                              f'с известной отраслью: фактор «{f[1].lower()}» доходит до компании через них')

    geo = fid.get('geo', 'card.region')
    add(('бюджет_и_налоги', f'Регион: {card["region"]}', 'региональные меры поддержки, налоги и инфраструктура',
         [card['region'], f'{card["region"]} экономика', f'{card["region"]} губернатор']), 0.4, 'geo:region', [geo])
    return sorted(out.values(), key=lambda x: -x['weight'])


def search_terms(card: dict) -> dict[str, list[str]]:
    """Goods and inputs of the sector: plain words for news retrieval (not OKVED names)."""
    _, (goods, inputs, _) = sector_entry(card['okved'])
    return {'goods': goods, 'inputs': inputs}
